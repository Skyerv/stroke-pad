/**
 * Dev-time generator: converts the HSK Standard Course vocabulary CSVs into the
 * per-book data modules consumed by `src/data/hsk/index.js`.
 *
 * Usage:
 *   node scripts/generate-hsk-data.js [path-to-csv-dir]
 *   npm run generate:hsk -- [path-to-csv-dir]
 *
 * The CSVs are not committed to the repo; the generated `src/data/hsk/hsk-*.js`
 * files are. Re-run this whenever the source dataset changes.
 *
 * Rules (agreed with product):
 *  - Include only core "New Word" entries (Type === "new word", case-insensitive).
 *    This excludes Proper Nouns, Supplementary Vocabulary, "…Made Up of Characters
 *    Learned before", and out-of-syllabus words.
 *  - Load full words/phrases as-is (no character splitting).
 *  - 7 books with the 上/下 split, up to HSK 5. Lesson numbers are the real
 *    textbook lesson numbers (e.g. HSK 4下 = 11–20).
 */

const fs = require("fs");
const path = require("path");

const DEFAULT_CSV_DIR =
  "C:\\Users\\amand\\Downloads\\hsk_standard_course_vocab-main\\hsk_standard_course_vocab-main\\hsk_vocab";

const OUT_DIR = path.join(__dirname, "..", "src", "data", "hsk");

// Ordered: drives the Book dropdown order in the UI.
const BOOKS = [
  { tag: "hsk_1", id: "1", label: "HSK 1" },
  { tag: "hsk_2", id: "2", label: "HSK 2" },
  { tag: "hsk_3", id: "3", label: "HSK 3" },
  { tag: "hsk_4a", id: "4a", label: "HSK 4上" },
  { tag: "hsk_4b", id: "4b", label: "HSK 4下" },
  { tag: "hsk_5a", id: "5a", label: "HSK 5上" },
  { tag: "hsk_5b", id: "5b", label: "HSK 5下" },
];

/**
 * Minimal RFC-4180-ish CSV parser: handles quoted fields, commas inside quotes,
 * escaped double-quotes (""), and \r\n / \n line endings.
 * Returns an array of records, each an array of string fields.
 */
function parseCsv(text) {
  const rows = [];
  let field = "";
  let record = [];
  let inQuotes = false;

  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];

    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 1;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
      continue;
    }

    if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      record.push(field);
      field = "";
    } else if (c === "\n") {
      record.push(field);
      rows.push(record);
      record = [];
      field = "";
    } else if (c === "\r") {
      // ignore; handled by the following \n
    } else {
      field += c;
    }
  }

  if (field.length > 0 || record.length > 0) {
    record.push(field);
    rows.push(record);
  }

  return rows;
}

function toObjects(rows) {
  if (rows.length === 0) {
    return [];
  }
  const header = rows[0].map((h) => h.trim());
  return rows.slice(1).map((cells) => {
    const obj = {};
    header.forEach((key, idx) => {
      obj[key] = cells[idx] !== undefined ? cells[idx] : "";
    });
    return obj;
  });
}

function findCsvForTag(csvDir, tag) {
  const files = fs.readdirSync(csvDir);
  const match = files.find((name) => name.toLowerCase().endsWith(`${tag}.csv`));
  if (!match) {
    throw new Error(`No CSV found for ${tag} in ${csvDir}`);
  }
  return path.join(csvDir, match);
}

function parseLessonNumber(lessonField) {
  const value = String(lessonField || "").trim();
  const dot = value.indexOf(".");
  if (dot === -1) {
    return null;
  }
  const lesson = Number.parseInt(value.slice(dot + 1), 10);
  return Number.isNaN(lesson) ? null : lesson;
}

function buildLessons(csvPath) {
  const text = fs.readFileSync(csvPath, "utf8");
  const records = toObjects(parseCsv(text));

  const lessons = {};
  const seenByLesson = {};

  for (const row of records) {
    const type = String(row["Type"] || "").trim().toLowerCase();
    if (type !== "new word") {
      continue;
    }

    const lesson = parseLessonNumber(row["Lesson"]);
    if (lesson === null) {
      continue;
    }

    const word = String(row["Word/Phrase"] || "").trim();
    if (!word) {
      continue;
    }

    if (!lessons[lesson]) {
      lessons[lesson] = [];
      seenByLesson[lesson] = new Set();
    }
    if (!seenByLesson[lesson].has(word)) {
      seenByLesson[lesson].add(word);
      lessons[lesson].push(word);
    }
  }

  return lessons;
}

function emitBookModule(book, lessons) {
  const varName = `hsk${book.id}`;
  const numbers = Object.keys(lessons)
    .map(Number)
    .sort((a, b) => a - b);

  const lines = [];
  lines.push("// AUTO-GENERATED by scripts/generate-hsk-data.js — do not edit by hand.");
  lines.push(`const ${varName} = {`);
  lines.push(`  id: ${JSON.stringify(book.id)},`);
  lines.push(`  label: ${JSON.stringify(book.label)},`);
  lines.push("  lessons: {");
  for (const n of numbers) {
    lines.push(`    ${JSON.stringify(String(n))}: [`);
    for (const word of lessons[n]) {
      lines.push(`      ${JSON.stringify(word)},`);
    }
    lines.push("    ],");
  }
  lines.push("  },");
  lines.push("};");
  lines.push("");
  lines.push(`module.exports = { ${varName} };`);
  lines.push("");

  return lines.join("\n");
}

function main() {
  const csvDir = process.argv[2] || DEFAULT_CSV_DIR;

  if (!fs.existsSync(csvDir)) {
    console.error(`CSV directory not found: ${csvDir}`);
    console.error("Pass the dataset path: node scripts/generate-hsk-data.js <path-to-csv-dir>");
    process.exit(1);
  }

  console.log(`Reading CSVs from: ${csvDir}\n`);

  for (const book of BOOKS) {
    const csvPath = findCsvForTag(csvDir, book.tag);
    const lessons = buildLessons(csvPath);
    const outPath = path.join(OUT_DIR, `hsk-${book.id}.js`);
    fs.writeFileSync(outPath, emitBookModule(book, lessons), "utf8");

    const lessonCount = Object.keys(lessons).length;
    const wordCount = Object.values(lessons).reduce((sum, arr) => sum + arr.length, 0);
    console.log(
      `  ${book.label.padEnd(8)} → hsk-${book.id}.js  (${lessonCount} lessons, ${wordCount} words)`
    );
  }

  console.log("\nDone.");
}

main();
